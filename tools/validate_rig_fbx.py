r"""
validate_rig_fbx.py -- headless Blender gate that FAILS a creature FBX whose
skeleton is anatomically incoherent, BEFORE it can reach Unreal and the game.

WHY THIS EXISTS
The W2.1b "quality rebuild" shipped a rig whose two legs were named as if
from different limb groups, with no pelvis, an asymmetric stance, and the
tail hanging off a limb chain. Nothing checked it, so it cooked, shipped,
and surfaced only as the user watching a creature whose "leg kicks up and
down" -- three sessions and several builds later. Same lesson as
check_imports.ps1 and the spatial self-tests: a bug we have paid for once
becomes a GATE, not a memory.

This validator is deliberately independent of whoever authored the rig: it
re-derives every fact from the FBX itself rather than trusting an export
report.

USAGE (exit code 0 = pass, 1 = fail; every finding printed as PFARIG ...):
    "C:\Blender\Blender 5.2\blender.exe" --background --factory-startup ^
      --python "C:/Claude/Projects/PrimalFauna/tools/validate_rig_fbx.py" ^
      -- "C:/path/to/SK_Creature.fbx" [--manifest "C:/path/out/rig_manifest.json"]

A passing run also writes the manifest (bone list + parents + mirrored
pairs), which the UE import step can assert against so a LATER rig swap
cannot silently change the skeleton under the animations.
"""
import json
import math
import os
import sys

import bpy


# --- role patterns: a creature rig must express these, however it names them.
# Matching is case-insensitive substring, so Thigh/UpperLeg/upper_leg all pass.
REQUIRED_ROLES = {
    "pelvis_or_hip": ("pelvis", "hip"),
    "spine": ("spine", "back"),
    "head": ("head", "skull"),
    "thigh": ("thigh", "upperleg", "upper_leg", "femur"),
    "shin": ("calf", "shin", "lowerleg", "lower_leg", "tibia"),
    "foot": ("foot", "ankle"),
}

# Left/right markers, checked as delimited tokens so "Left"/"_L_"/".L" match
# but the L in "Clavicle" does not.
LEFT_TOKENS = ("left", "_l_", ".l", "-l-", "l_")
RIGHT_TOKENS = ("right", "_r_", ".r", "-r-", "r_")

# A bone whose name matches these is unnamed-in-practice: Blender/importer
# autogenerated filler that means the rig was never authored deliberately.
JUNK_NAME_PREFIXES = ("bone", "bone.", "armature", "object", "node")

MIRROR_TOLERANCE_M = 0.02   # 2cm: mirrored bones must sit symmetrically in X
MIN_RIG_HEIGHT_M = 0.2
MAX_RIG_HEIGHT_M = 20.0

failures = []
warnings = []


def log(msg):
    print("PFARIG " + msg)


def fail(msg):
    failures.append(msg)
    print("PFARIG FAIL: " + msg)


def warn(msg):
    warnings.append(msg)
    print("PFARIG WARN: " + msg)


def side_of(name):
    lowered = name.lower()
    for token in LEFT_TOKENS:
        if token in lowered:
            return "L"
    for token in RIGHT_TOKENS:
        if token in lowered:
            return "R"
    return None


def mirror_name(name):
    """Best-effort L<->R name flip, tolerant of the common conventions."""
    swaps = [("left", "right"), ("Left", "Right"), ("LEFT", "RIGHT"),
             ("_l_", "_r_"), ("_L_", "_R_"), (".l", ".r"), (".L", ".R"),
             ("l_", "r_"), ("L_", "R_")]
    lowered = name.lower()
    is_left = any(t in lowered for t in LEFT_TOKENS)
    for left_form, right_form in swaps:
        if is_left and left_form in name:
            return name.replace(left_form, right_form, 1)
        if not is_left and right_form in name:
            return name.replace(right_form, left_form, 1)
    return None


def parse_args():
    argv = sys.argv
    if "--" not in argv:
        print("PFARIG FAIL: no FBX path given (pass it after --)")
        sys.exit(1)
    args = argv[argv.index("--") + 1:]
    fbx = args[0]
    manifest = None
    if "--manifest" in args:
        manifest = args[args.index("--manifest") + 1]
    return fbx, manifest


def main():
    fbx_path, manifest_path = parse_args()
    if not os.path.isfile(fbx_path):
        fail("FBX not found: %s" % fbx_path)
        sys.exit(1)

    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.fbx(filepath=fbx_path)
    log("loaded %s" % fbx_path)

    armatures = [o for o in bpy.data.objects if o.type == "ARMATURE"]
    if len(armatures) != 1:
        fail("expected exactly ONE armature, found %d (%s)"
             % (len(armatures), ", ".join(o.name for o in armatures) or "none"))
        sys.exit(1)
    armature = armatures[0]

    # Satisfactory modding docs + community: the armature OBJECT must be named
    # "Armature" or Unreal synthesises an extra root bone and the hierarchy
    # stops matching anything.
    if armature.name != "Armature":
        warn("armature object is named '%s', not 'Armature' -- UE may add an extra root bone"
             % armature.name)

    bones = list(armature.data.bones)
    log("armature '%s' bones=%d dims=(%.3f, %.3f, %.3f)m"
        % (armature.name, len(bones), armature.dimensions.x, armature.dimensions.y, armature.dimensions.z))

    if not bones:
        fail("armature has NO bones")
        sys.exit(1)

    names = [b.name for b in bones]
    lowered_names = [n.lower() for n in names]

    # --- 1. exactly one root -------------------------------------------------
    roots = [b.name for b in bones if b.parent is None]
    if len(roots) != 1:
        fail("expected exactly ONE root bone, found %d: %s" % (len(roots), ", ".join(roots)))
    else:
        log("root bone = %s" % roots[0])

    # --- 2. no junk/auto names ----------------------------------------------
    for name in names:
        stripped = name.strip()
        if not stripped:
            fail("a bone has an EMPTY name")
            continue
        low = stripped.lower()
        if any(low == p or low.startswith(p) and low[len(p):].replace(".", "").isdigit()
               for p in JUNK_NAME_PREFIXES):
            fail("bone '%s' has an auto-generated/placeholder name -- rig was not authored deliberately" % name)

    # --- 3. required anatomical roles ---------------------------------------
    for role, patterns in REQUIRED_ROLES.items():
        hits = [n for n, low in zip(names, lowered_names) if any(p in low for p in patterns)]
        if not hits:
            fail("no bone expresses the required role '%s' (looked for %s)" % (role, "/".join(patterns)))
        else:
            log("role %-14s -> %d bone(s), e.g. %s" % (role, len(hits), hits[0]))

    # --- 4. left/right symmetry ---------------------------------------------
    sided = [(n, side_of(n)) for n in names]
    left_names = [n for n, s in sided if s == "L"]
    right_names = [n for n, s in sided if s == "R"]
    log("sided bones: L=%d R=%d unsided=%d" % (len(left_names), len(right_names),
                                               len(names) - len(left_names) - len(right_names)))
    if len(left_names) != len(right_names):
        fail("asymmetric rig: %d left-sided bones vs %d right-sided" % (len(left_names), len(right_names)))

    by_name = {b.name: b for b in bones}
    mirrored_pairs = []
    for left_name in left_names:
        expected = mirror_name(left_name)
        if not expected or expected not in by_name:
            fail("left bone '%s' has NO right-side counterpart (expected '%s')"
                 % (left_name, expected or "<unmappable name>"))
            continue
        left_head = by_name[left_name].head_local
        right_head = by_name[expected].head_local
        # Mirrored about X: same Y/Z, opposite X.
        dx = abs(left_head.x + right_head.x)
        dyz = math.hypot(left_head.y - right_head.y, left_head.z - right_head.z)
        if dx > MIRROR_TOLERANCE_M or dyz > MIRROR_TOLERANCE_M:
            fail("'%s' and '%s' are NOT mirrored (|Lx+Rx|=%.3fm, YZ delta=%.3fm, tolerance %.3fm)"
                 % (left_name, expected, dx, dyz, MIRROR_TOLERANCE_M))
        else:
            mirrored_pairs.append([left_name, expected])

    # --- 5. both legs live in the SAME named chain family --------------------
    # This is the exact W2.1b defect: legs named from different limb groups,
    # so a name-driven retarget fed one leg slot with arm motion.
    def chain_root_of(bone):
        node = bone
        while node.parent is not None:
            node = node.parent
        return node.name

    def find_role_bone(patterns, side):
        for name, low in zip(names, lowered_names):
            if any(p in low for p in patterns) and side_of(name) == side:
                return by_name[name]
        return None

    left_thigh = find_role_bone(REQUIRED_ROLES["thigh"], "L")
    right_thigh = find_role_bone(REQUIRED_ROLES["thigh"], "R")
    if left_thigh and right_thigh:
        left_parent = left_thigh.parent.name if left_thigh.parent else "<root>"
        right_parent = right_thigh.parent.name if right_thigh.parent else "<root>"
        if left_parent != right_parent:
            fail("the two legs attach to DIFFERENT parents ('%s' vs '%s') -- they must share a pelvis/hip"
                 % (left_parent, right_parent))
        else:
            log("both thighs parent to '%s'" % left_parent)
    else:
        fail("could not identify a left AND right thigh bone -- leg naming is not symmetric/role-based")

    # --- 6. tail (if present) must hang off the pelvis/hip, not a limb -------
    tail_bones = [n for n, low in zip(names, lowered_names) if "tail" in low]
    if tail_bones:
        tail_root = None
        for name in tail_bones:
            bone = by_name[name]
            if not bone.parent or bone.parent.name not in tail_bones:
                tail_root = bone
                break
        if tail_root is not None:
            parent_name = tail_root.parent.name.lower() if tail_root.parent else "<root>"
            if not any(p in parent_name for p in ("pelvis", "hip", "spine", "root")):
                fail("tail root '%s' parents to '%s' -- a tail must hang off the pelvis/hip/spine, not a limb"
                     % (tail_root.name, tail_root.parent.name if tail_root.parent else "<root>"))
            else:
                log("tail chain (%d bones) roots at '%s' under '%s'"
                    % (len(tail_bones), tail_root.name, tail_root.parent.name if tail_root.parent else "<root>"))

    # --- 7. scale sanity (the 1.65cm trap, caught before UE ever sees it) ----
    height = armature.dimensions.z
    if not (MIN_RIG_HEIGHT_M <= height <= MAX_RIG_HEIGHT_M):
        fail("rig height %.3fm is outside the sane creature range [%.1f, %.1f]m -- unit-scale/export problem"
             % (height, MIN_RIG_HEIGHT_M, MAX_RIG_HEIGHT_M))

    # --- verdict -------------------------------------------------------------
    if manifest_path and not failures:
        manifest = {
            "source_fbx": fbx_path,
            "armature": armature.name,
            "bone_count": len(bones),
            "height_m": round(height, 4),
            "root": roots[0] if len(roots) == 1 else None,
            "bones": [{"name": b.name, "parent": b.parent.name if b.parent else None} for b in bones],
            "mirrored_pairs": mirrored_pairs,
        }
        os.makedirs(os.path.dirname(manifest_path), exist_ok=True)
        with open(manifest_path, "w", encoding="utf-8") as handle:
            json.dump(manifest, handle, indent=2)
        log("manifest written: %s" % manifest_path)

    log("SUMMARY failures=%d warnings=%d bones=%d" % (len(failures), len(warnings), len(bones)))
    if failures:
        log("VERDICT: REJECT -- do not import this rig")
        sys.exit(1)
    log("VERDICT: ACCEPT")


main()
